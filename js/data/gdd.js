/** Nombre total de chapitres (sous-sections comprises). */
export function countChapters() {
  return TOMES.reduce((total, tome) => {
    return (
      total +
      tome.chapters.reduce((sub, ch) => sub + 1 + (ch.subsections ? ch.subsections.length : 0), 0)
    );
  }, 0);
}

/** Nombre total de puces/exigences atomiques recensées dans le corpus. */
export function countRequirements() {
  let n = 0;
  for (const tome of TOMES) {
    for (const ch of tome.chapters) {
      n += (ch.bullets || []).length;
      for (const sub of ch.subsections || []) n += (sub.bullets || []).length;
    }
  }
  return n;
}

/** Retrouve un tome par son identifiant. */
export function getTome(id) {
  return TOMES.find((t) => t.id === id) || null;
}
