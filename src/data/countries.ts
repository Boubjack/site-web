const COUNTRY_INDEX = new Map(COUNTRIES.map((country) => [country.id, country]));

export function getCountry(id: string): CountryDef {
  const country = COUNTRY_INDEX.get(id);
  if (!country) throw new Error(`Pays inconnu : "${id}"`);
  return country;
}

export function findCountry(id: string): CountryDef | undefined {
  return COUNTRY_INDEX.get(id);
}

export function countriesByContinent(continent: Continent): CountryDef[] {
  return COUNTRIES.filter((country) => country.continent === continent);
}
